"""Downlink digest vs send-everything (items or bytes); check-in time; alerts per day.

    python -m evidence.downlink_efficiency [--seed 42] [--no-write]

Runs storm_day and normal_day through the real CLI scenario runner, queues
every record's summary in the real DownlinkQueue, and for each link profile
(LEO, Moon, Mars near, Mars far) reports:

  - what goes out immediately vs what waits for the periodic digest
    (RED/GREY/YELLOW always go at once; GREEN is held on a long link)
  - bytes on the wire: summaries+anchors vs sending every full Record

Also measures wall-clock time per decide() call on this machine (median and
worst over the scenario events) and alerts (non-GREEN verdicts) per
scenario day. Timing numbers are from this run on this machine only.

Scenarios are simulated drafts; limits are project-defined placeholders.

Owner: person D
"""

from __future__ import annotations

import argparse
import random
import statistics
import sys
import tempfile
import time
from pathlib import Path

from backend.api.state import load_all_baselines
from backend.cli import run_scenario
from backend.downlink.delay import DISTANCES_KM, delay_for
from backend.downlink.queue import DownlinkQueue, payload_bytes
from backend.orchestrator import decide, load_rules
from evidence._harness import SCENARIOS, load_scenario, parse_ts, write_results

LOCATIONS = ("leo", "moon", "mars_near", "mars_far")


def _records(seed: int) -> list[dict]:
    with tempfile.TemporaryDirectory() as tmp:
        store = str(Path(tmp) / "records.db")
        records = []
        for name in ("storm_day", "normal_day"):
            records += run_scenario(str(SCENARIOS / f"{name}.json"), seed=seed,
                                    store_path=store, out_dir=tmp)
        return records


def _queue_stats(records: list[dict], location: str) -> dict:
    delay = delay_for(location)
    queue = DownlinkQueue()
    for record in records:
        queue.enqueue(record)
    anchors_bytes = sum(payload_bytes(a) for a in queue.anchors())
    immediate = queue.release(delay)
    held = queue.pending()
    digest = queue.release(delay, flush=True)
    summary_bytes = sum(payload_bytes(s) for s in immediate + digest) + anchors_bytes
    full_bytes = sum(payload_bytes(r) for r in records)
    return {
        "location": location,
        "one_way_delay_s": round(delay, 2),
        "sent_immediately": len(immediate),
        "held_for_digest": len(held),
        "summary_and_anchor_bytes": summary_bytes,
        "full_record_bytes": full_bytes,
        "bytes_ratio": round(summary_bytes / full_bytes, 3) if full_bytes else None,
    }


def _checkin_timing(seed: int) -> dict:
    """Wall-clock decide() per event, on this machine, this run."""
    random.seed(seed)
    rules = load_rules()
    baselines = load_all_baselines(None)
    times = []
    prev_hash = "GENESIS"
    for name in ("storm_day", "normal_day"):
        for event in load_scenario(name)["events"]:
            start = time.perf_counter()
            record = decide(event["readings"], baselines, rules, parse_ts(event["ts"]),
                            prev_hash=prev_hash)
            times.append(time.perf_counter() - start)
            prev_hash = record["hash"]
    return {
        "events": len(times),
        "median_s": round(statistics.median(times), 4),
        "max_s": round(max(times), 4),
    }


def run(seed: int = 42) -> dict:
    random.seed(seed)
    records = _records(seed)
    alerts = {}
    for name in ("storm_day", "normal_day"):
        # Both scenarios use crew_1, so attribute records by scenario day.
        day = load_scenario(name)["events"][0]["ts"][:10]
        scenario_records = [r for r in records if r["ts"][:10] == day]
        alerts[name] = sum(r["verdict"]["tier"] != "GREEN" for r in scenario_records)

    return {
        "seed": seed,
        "records": len(records),
        "links": [_queue_stats(records, loc) for loc in LOCATIONS],
        "distances_km": {k: DISTANCES_KM[k] for k in LOCATIONS},
        "checkin_timing": _checkin_timing(seed),
        "alerts_per_scenario_day": alerts,
    }


def to_markdown(data: dict) -> str:
    t = data["checkin_timing"]
    lines = [
        "# Downlink efficiency",
        "",
        f"Generated by `python -m evidence.downlink_efficiency` over {data['records']}",
        "records from the storm_day and normal_day draft scenarios. Bytes compare",
        "the queue's summaries plus signed chain anchors against sending every",
        "full Record. RED/GREY/YELLOW go immediately on every link; GREEN waits",
        "for the digest only when the one-way delay exceeds 60 s.",
        "",
        "| Link | One-way delay | Sent at once | Held for digest | Summary+anchor bytes | Full-record bytes | Ratio |",
        "|---|---|---|---|---|---|---|",
    ]
    for link in data["links"]:
        lines.append(
            f"| {link['location']} | {link['one_way_delay_s']} s | {link['sent_immediately']} | "
            f"{link['held_for_digest']} | {link['summary_and_anchor_bytes']} | "
            f"{link['full_record_bytes']} | {link['bytes_ratio']} |"
        )
    lines += [
        "",
        f"decide() per check-in on this machine, this run: median {t['median_s']} s, "
        f"worst {t['max_s']} s over {t['events']} events (LLM disabled).",
        "",
        "Alerts (non-GREEN verdicts) per scenario day: "
        + ", ".join(f"{k} {v}" for k, v in data["alerts_per_scenario_day"].items())
        + ".",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--no-write", action="store_true")
    args = parser.parse_args(argv)

    data = run(seed=args.seed)
    print(to_markdown(data))
    if not args.no_write:
        write_results("downlink_efficiency", to_markdown(data), data)
    return 0


if __name__ == "__main__":
    sys.exit(main())
