"""Move every threshold +/-20% and report unsafe approvals.

    python -m evidence.sensitivity [--seed 42] [--no-write]

Every numeric bound in the limits table (yellow_low/high, red_low/high) is
multiplied by 0.8, 0.9, 1.0, 1.1 and 1.2. For each factor the FULL system
(input gate, blind pipelines, Checker) is run over:

  - the pure-data red-team check-in cases  -> unsafe approvals
  - storm_day.json                         -> which event first goes non-GREEN
  - normal_day.json                        -> false alarms on a quiet day

The point being tested: the integrity answers (GREY on stale, stuck,
contradictory or unverifiable data) must not depend on where the
project-defined placeholder thresholds sit, because they come from the input
gate and Checker, not the limits table. Tier answers for in-range values MAY
move with the thresholds - that is what thresholds do - and the table shows
by how much, which is the margin argument for sourcing the limits properly.

Scenarios are simulated drafts; the limits are project-defined placeholders,
not NASA medical limits.

Owner: person D
"""

from __future__ import annotations

import argparse
import copy
import logging
import random
import sys
import tempfile
from pathlib import Path

import yaml

from backend.orchestrator import DEFAULT_LIMITS_PATH
from evidence._harness import (
    condition_tier,
    default_rules_and_baselines,
    is_unsafe,
    load_scenario,
    pure_data_attacks,
    run_scenario_tiers,
    write_results,
)

FACTORS = (0.8, 0.9, 1.0, 1.1, 1.2)
_BOUNDS = ("yellow_low", "yellow_high", "red_low", "red_high")


def scaled_limits(factor: float) -> dict:
    """The default limits table with every numeric bound multiplied by *factor*.

    Scaling can make a band inconsistent (e.g. a scaled yellow_low above the
    channel's typical value); that is part of what the sweep probes.
    """
    limits = yaml.safe_load(DEFAULT_LIMITS_PATH.read_text(encoding="utf-8"))
    scaled = copy.deepcopy(limits)
    for row in (scaled.get("channels") or {}).values():
        for bound in _BOUNDS:
            if row.get(bound) is not None:
                row[bound] = round(float(row[bound]) * factor, 6)
    return scaled


def run(seed: int = 42) -> dict:
    random.seed(seed)
    storm = load_scenario("storm_day")
    normal = load_scenario("normal_day")
    attacks = pure_data_attacks()

    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        for factor in FACTORS:
            limits_file = Path(tmp) / f"limits_{factor}.yaml"
            limits_file.write_text(yaml.safe_dump(scaled_limits(factor)), encoding="utf-8")
            rules, baselines = default_rules_and_baselines(limits_file=str(limits_file))

            attack_rows = []
            for attack in attacks:
                logging.disable(logging.CRITICAL)
                try:
                    observed = condition_tier("full", attack["readings"], rules, baselines,
                                              attack["now"], astronaut_id=attack["astronaut_id"])
                finally:
                    logging.disable(logging.NOTSET)
                attack_rows.append({
                    "id": attack["id"],
                    "observed": observed,
                    "allowed": attack["allowed_tiers"],
                    "unsafe": is_unsafe(observed, attack["allowed_tiers"]),
                })

            storm_tiers = run_scenario_tiers("full", storm, rules, baselines)
            normal_tiers = run_scenario_tiers("full", normal, rules, baselines)
            rows.append({
                "factor": factor,
                "unsafe_approvals": sum(r["unsafe"] for r in attack_rows),
                "attacks": attack_rows,
                "storm_tiers": storm_tiers,
                "storm_first_non_green_event": next(
                    (i for i, r in enumerate(storm_tiers) if r["tier"] != "GREEN"), None),
                "normal_false_alarms": sum(r["tier"] != "GREEN" for r in normal_tiers),
            })

    return {"seed": seed, "attack_count": len(attacks), "factors": rows}


def to_markdown(data: dict) -> str:
    lines = [
        "# Threshold sensitivity",
        "",
        "Generated by `python -m evidence.sensitivity`. Every numeric bound of the",
        "project-defined limits table is scaled by the factor; the full system is",
        f"then run over the {data['attack_count']} pure-data red-team check-in cases and the",
        "two draft scenarios. Integrity verdicts (GREY on stale, stuck, contradictory",
        "or unverifiable data) must not move with the thresholds. Tier verdicts on",
        "plausible values may: a case that crossed a red bound at x1.0 can sit under",
        "the loosened bound at x1.2, which measures how close those attack values",
        "are to the placeholder limits.",
        "",
        "| Factor | Unsafe approvals | Storm: first non-GREEN event | Quiet-day false alarms |",
        "|---|---|---|---|",
    ]
    for row in data["factors"]:
        first = row["storm_first_non_green_event"]
        lines.append(
            f"| x{row['factor']} | {row['unsafe_approvals']} of {data['attack_count']} | "
            f"{'never' if first is None else f'event {first}'} | {row['normal_false_alarms']} |"
        )
    lines += ["", "Per-attack and per-event outcomes are in `sensitivity.json`.", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--no-write", action="store_true")
    args = parser.parse_args(argv)

    data = run(seed=args.seed)
    print(to_markdown(data))
    if not args.no_write:
        write_results("sensitivity", to_markdown(data), data)
    return 0


if __name__ == "__main__":
    sys.exit(main())
