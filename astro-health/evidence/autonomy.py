"""Delay-aware autonomy: which decisions the crew must own alone, by distance from Earth.

    python -m evidence.autonomy [--seed 42] [--no-write]

Runs storm_day and normal_day through the real CLI scenario runner, then, for
each link (LEO, Moon, Mars near, Mars far), computes the real handoff for every
recorded verdict with backend.records.handoff.assess and reports:

  - how many decisions were GROUND_IN_LOOP, ONBOARD_AUTHORITY or ROUTINE
  - for each authorized action, whether Earth could answer before its deadline

The verdicts are computed once and never depend on the link: delay changes who
can take part in a decision, not the decision. Deadlines and the ground
turnaround are project-defined placeholders (backend/checker/autonomy.yaml);
scenarios are simulated drafts; limits are project-defined placeholders.

Owner: person D
"""

from __future__ import annotations

import argparse
import sys

from backend.records.handoff import assess, link_for, load_autonomy_policy
from evidence._harness import write_results
from evidence.downlink_efficiency import LOCATIONS, _records

ACTIONS = ("NO_ACTION", "RECHECK_IN_1H", "REST_AND_HYDRATE", "USE_PROTOCOL_CARD", "ALERT_CMO", "CONTACT_GROUND_URGENT")
MODES = ("GROUND_IN_LOOP", "ONBOARD_AUTHORITY", "ROUTINE")


def run(seed: int = 42) -> dict:
    policy, digest = load_autonomy_policy()
    records = _records(seed)
    links = []
    for loc in LOCATIONS:
        link = link_for(loc)
        counts = {m: 0 for m in MODES}
        for record in records:
            counts[assess(record, link, policy, digest)["mode"]] += 1
        alerts = [r for r in records if r["verdict"]["tier"] != "GREEN"]
        alone = sum(assess(r, link, policy, digest)["mode"] == "ONBOARD_AUTHORITY" for r in alerts)
        links.append({
            "location": loc,
            "label": link["label"],
            "one_way_delay_s": round(link["one_way_delay_s"], 2),
            "earth_answer_s": round(2 * link["one_way_delay_s"] + policy["ground_turnaround_s"], 1),
            "counts": counts,
            "alerts": len(alerts),
            "alerts_owned_onboard": alone,
        })

    matrix = []
    for action in ACTIONS:
        probe = {"id": "probe", "astronaut_id": "probe", "ts": "2026-11-14T00:00:00Z",
                 "verdict": {"tier": "GREEN" if action == "NO_ACTION" else "RED", "action": action}}
        matrix.append({
            "action": action,
            "deadline_s": policy["action_deadline_s"][action],
            "modes": {loc: assess(probe, link_for(loc), policy, digest)["mode"] for loc in LOCATIONS},
        })

    return {
        "seed": seed,
        "records": len(records),
        "ground_turnaround_s": policy["ground_turnaround_s"],
        "autonomy_policy_hash": digest,
        "links": links,
        "action_matrix": matrix,
    }


def _dur(s: float | None) -> str:
    if s is None:
        return "none"
    if s < 60:
        return f"{s:.1f} s"
    if s < 3600:
        return f"{s / 60:.1f} min"
    return f"{s / 3600:.2f} h"


_WORD = {"GROUND_IN_LOOP": "ground in loop", "ONBOARD_AUTHORITY": "**onboard alone**", "ROUTINE": "routine"}


def to_markdown(data: dict) -> str:
    out = [
        "# Delay-aware autonomy",
        "",
        "Generated by `python -m evidence.autonomy`. For every recorded verdict in storm_day and",
        "normal_day, and for each distance from Earth, the real handoff says whether Earth's answer",
        f"(round-trip light time + {_dur(data['ground_turnaround_s'])} assumed ground turnaround) arrives",
        "before the verdict's action has to start. Verdicts are identical at every distance: delay",
        "changes who can take part in a decision, never the decision.",
        "",
        "Deadlines and turnaround are project-defined placeholders (`backend/checker/autonomy.yaml`),",
        "scenarios are simulated drafts, limits are project-defined placeholders.",
        "",
        f"## Decisions over {data['records']} recorded verdicts",
        "",
        "| Link | One way | Earth's answer | Ground in loop | Onboard alone | Routine | Alerts owned onboard |",
        "|---|---|---|---|---|---|---|",
    ]
    for row in data["links"]:
        c = row["counts"]
        out.append(
            f"| {row['label']} | {_dur(row['one_way_delay_s'])} | {_dur(row['earth_answer_s'])} | "
            f"{c['GROUND_IN_LOOP']} | {c['ONBOARD_AUTHORITY']} | {c['ROUTINE']} | "
            f"{row['alerts_owned_onboard']} of {row['alerts']} |"
        )
    labels = [row["label"] for row in data["links"]]
    out += [
        "",
        "## Who can decide in time, by action",
        "",
        "| Action | Must start within | " + " | ".join(labels) + " |",
        "|---|---|" + "---|" * len(labels),
    ]
    for row in data["action_matrix"]:
        cells = [_WORD[row["modes"][loc]] for loc in LOCATIONS]
        out.append(f"| {row['action']} | {_dur(row['deadline_s'])} | " + " | ".join(cells) + " |")
    out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--no-write", action="store_true")
    args = parser.parse_args(argv)
    data = run(seed=args.seed)
    md = to_markdown(data)
    if not args.no_write:
        write_results("autonomy", md, data)
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
