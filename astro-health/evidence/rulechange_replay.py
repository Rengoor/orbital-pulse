"""Runs backend/earth/rulechange.py over past decisions; writes the rule-change table.

    python -m evidence.rulechange_replay [--seed 42] [--no-write]

Builds a day of past decisions (storm_day then normal_day through the real
CLI scenario runner, records chained in a temporary store), then asks the
time machine what three candidate rule changes would have done to them:

  tighten_dose    dose_rate_usv_h yellow_high 50 -> 40, red_high 200 -> 160
  loosen_dose     dose_rate_usv_h yellow_high 50 -> 80, red_high 200 -> 320
  tighten_sleep   sleep_hours yellow_low 6 -> 6.5

Nothing is stored and no past Record is altered: rulechange() replays each
record under the proposed rules and reports which decisions change and which
would have been LESS severe than the decision actually taken (the unsafe
rows a reviewer must read before accepting the change).

Scenarios are simulated drafts; all limits are project-defined placeholders.

Owner: person D
"""

from __future__ import annotations

import argparse
import copy
import random
import sys
import tempfile
from pathlib import Path

from backend.api.state import load_all_baselines
from backend.cli import run_scenario
from backend.earth.rulechange import rulechange
from backend.orchestrator import load_rules
from evidence._harness import SCENARIOS, write_results

PROPOSALS = {
    "tighten_dose": {"dose_rate_usv_h": {"yellow_high": 40, "red_high": 160}},
    "loosen_dose": {"dose_rate_usv_h": {"yellow_high": 80, "red_high": 320}},
    "tighten_sleep": {"sleep_hours": {"yellow_low": 6.5}},
}


def _proposed_rules(changes: dict) -> dict:
    rules = load_rules()
    limits = copy.deepcopy(rules["limits"])
    for channel, bounds in changes.items():
        limits["channels"][channel].update(bounds)
    rules["limits"] = limits
    return rules


def run(seed: int = 42) -> dict:
    random.seed(seed)
    baselines = load_all_baselines(None)

    with tempfile.TemporaryDirectory() as tmp:
        store = str(Path(tmp) / "records.db")
        records = []
        for name in ("storm_day", "normal_day"):
            records += run_scenario(str(SCENARIOS / f"{name}.json"), seed=seed,
                                    store_path=store, out_dir=tmp)

        proposals = {}
        for name, changes in PROPOSALS.items():
            report = rulechange(records, baselines, _proposed_rules(changes))
            proposals[name] = {"changes": changes, **report}

    return {"seed": seed, "records": len(records), "proposals": proposals}


def to_markdown(data: dict) -> str:
    lines = [
        "# Rule-change replay",
        "",
        f"Generated by `python -m evidence.rulechange_replay` over {data['records']}",
        "chained records from the storm_day and normal_day draft scenarios.",
        "`unsafe` counts records where the proposed rules would have produced a",
        "less severe tier than the decision actually taken.",
        "",
        "| Proposal | Change | Records | Changed | Unsafe |",
        "|---|---|---|---|---|",
    ]
    for name, p in data["proposals"].items():
        change = "; ".join(
            f"{ch}.{bound} -> {value}" for ch, bounds in p["changes"].items()
            for bound, value in bounds.items()
        )
        lines.append(f"| {name} | {change} | {p['total']} | {p['changed']} | {p['unsafe']} |")
    lines += [
        "",
        "Per-record rows (old tier -> new tier) are in `rulechange_replay.json`.",
        "A loosening proposal showing unsafe rows is the mechanism working: those",
        "are exactly the decisions a reviewer must see before accepting the change.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--no-write", action="store_true")
    args = parser.parse_args(argv)

    data = run(seed=args.seed)
    print(to_markdown(data))
    if not args.no_write:
        write_results("rulechange_replay", to_markdown(data), data)
    return 0


if __name__ == "__main__":
    sys.exit(main())
