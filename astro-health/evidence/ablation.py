"""A only, B only, A+B, A+B+Checker, fixed-threshold baseline: detection delay, false alarms per day, unsafe approvals.

    python -m evidence.ablation [--seed 42] [--no-write]

Conditions:
  a_only           pipeline A alone, no input gate, no Checker
  b_only           pipeline B alone, no input gate, no Checker
  a_plus_b         worst of A and B, still no gate and no Checker
  fixed_threshold  values against the limits table only; quality, staleness,
                   units and contradictions ignored (the naive monitor)
  full             the real system: input gate, blind pipelines, Checker

Measured on:
  storm_day.json   detection: events from the first mechanical limit breach to
                   the first non-GREEN answer (simulated draft scenario)
  normal_day.json  false alarms: non-GREEN answers on an all-quiet day
  red-team cases   unsafe approvals on the pure-data attacks (the check-in
                   cases that need no LLM stub, pipeline kill or policy swap)

The limits are the project-defined placeholders, not NASA medical limits.
Report only what this run produced.

Owner: person D
"""

from __future__ import annotations

import argparse
import logging
import random
import sys

from evidence._harness import (
    CONDITIONS,
    condition_tier,
    default_rules_and_baselines,
    is_unsafe,
    load_scenario,
    parse_ts,
    pure_data_attacks,
    run_scenario_tiers,
    truth_breach_indices,
    write_results,
)


def run(seed: int = 42) -> dict:
    random.seed(seed)
    rules, baselines = default_rules_and_baselines()
    storm = load_scenario("storm_day")
    normal = load_scenario("normal_day")
    attacks = pure_data_attacks()

    breaches = truth_breach_indices(storm, rules["limits"])
    onset = breaches[0] if breaches else None

    results = {}
    for condition in CONDITIONS:
        storm_tiers = run_scenario_tiers(condition, storm, rules, baselines)
        normal_tiers = run_scenario_tiers(condition, normal, rules, baselines)

        detect_idx = next((i for i, row in enumerate(storm_tiers) if row["tier"] not in ("GREEN", "CRASHED")), None)
        if onset is None or detect_idx is None:
            delay_events = delay_hours = None
        else:
            delay_events = detect_idx - onset
            delay_hours = (parse_ts(storm_tiers[detect_idx]["ts"]) - parse_ts(storm_tiers[onset]["ts"])).total_seconds() / 3600

        false_alarms = sum(row["tier"] not in ("GREEN", "CRASHED") for row in normal_tiers)

        attack_rows = []
        for attack in attacks:
            # The attacks poke at exactly the failure modes the ablations lack
            # guards for; those crashes and warnings are the finding, not noise.
            logging.disable(logging.CRITICAL)
            try:
                observed = condition_tier(condition, attack["readings"], rules, baselines,
                                          attack["now"], astronaut_id=attack["astronaut_id"])
            finally:
                logging.disable(logging.NOTSET)
            attack_rows.append({
                "id": attack["id"],
                "observed": observed,
                "allowed": attack["allowed_tiers"],
                "unsafe": is_unsafe(observed, attack["allowed_tiers"]),
            })

        results[condition] = {
            "storm_tiers": storm_tiers,
            "normal_tiers": normal_tiers,
            "detection_delay_events": delay_events,
            "detection_delay_hours": delay_hours,
            "false_alarms_per_day": false_alarms,
            "attacks": attack_rows,
            "unsafe_approvals": sum(r["unsafe"] for r in attack_rows),
        }

    return {
        "seed": seed,
        "truth_breach_onset_event": onset,
        "attack_count": len(attacks),
        "conditions": results,
    }


def to_markdown(data: dict) -> str:
    lines = [
        "# Ablation results",
        "",
        "Generated by `python -m evidence.ablation`. Scenarios are simulated drafts;",
        "limits are the project-defined placeholders, not NASA medical limits.",
        f"Unsafe approvals are counted over the {data['attack_count']} pure-data red-team",
        "check-in cases (a CRASHED answer counts as unsafe: it protects no one).",
        "",
        "| Condition | Detection delay (events / h after first limit breach) | False alarms per quiet day | Unsafe approvals |",
        "|---|---|---|---|",
    ]
    for condition, r in data["conditions"].items():
        if r["detection_delay_events"] is None:
            delay = "never flagged"
        else:
            delay = f"{r['detection_delay_events']} / {r['detection_delay_hours']:.0f} h"
        lines.append(
            f"| {condition} | {delay} | {r['false_alarms_per_day']} | "
            f"{r['unsafe_approvals']} of {data['attack_count']} |"
        )
    lines += ["", "Per-attack outcomes are in `ablation.json`.", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--no-write", action="store_true")
    args = parser.parse_args(argv)

    data = run(seed=args.seed)
    print(to_markdown(data))
    if not args.no_write:
        write_results("ablation", to_markdown(data), data)
    return 0


if __name__ == "__main__":
    sys.exit(main())
